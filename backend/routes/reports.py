"""
ScamShield AI - Reports & Telemetry Router
Generates formal security incident reports, computes dynamic dashboard statistics
from actual stored records, serves threat intelligence, and exposes ML evaluation metrics.
"""
import os
import json
from fastapi import APIRouter, HTTPException, Depends
from typing import Optional
from backend.database.db import get_db_connection
from backend.routes.auth import get_current_user

router = APIRouter(prefix="/api", tags=["Reports & Intelligence"])

METRICS_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "models", "model_metrics.json")

@router.get("/report/{analysis_id}")
def get_report(analysis_id: str):
    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute("""
    SELECT id, user_id, input_type, input_preview, classification, risk_score, 
           risk_level, confidence, category, indicators, explanation, 
           recommendations, metadata, created_at
    FROM analyses
    WHERE id = ?
    """, (analysis_id,))
    row = cursor.fetchone()
    conn.close()

    if not row:
        raise HTTPException(status_code=404, detail="Incident report not found.")

    try:
        indicators = json.loads(row["indicators"]) if row["indicators"] else []
    except Exception:
        indicators = []
    try:
        recommendations = json.loads(row["recommendations"]) if row["recommendations"] else []
    except Exception:
        recommendations = []
    try:
        meta = json.loads(row["metadata"]) if row["metadata"] else {}
    except Exception:
        meta = {}

    return {
        "report_id": row["id"],
        "title": f"ScamShield AI Incident Assessment #{row['id']}",
        "timestamp": row["created_at"],
        "input_type": row["input_type"],
        "input_preview": row["input_preview"],
        "classification": row["classification"],
        "risk_score": row["risk_score"],
        "risk_level": row["risk_level"],
        "confidence": row["confidence"],
        "category": row["category"],
        "detected_indicators": indicators,
        "explanation": row["explanation"],
        "recommendations": recommendations,
        "metadata": meta,
        "compliance_notes": "Generated by ScamShield AI Advisory Engine. Strictly advisory in nature."
    }

@router.get("/stats")
def get_dashboard_stats():
    conn = get_db_connection()
    cursor = conn.cursor()

    # Total count
    cursor.execute("SELECT COUNT(*) FROM analyses")
    total_analyses = cursor.fetchone()[0]

    # Classification breakdown
    cursor.execute("SELECT classification, COUNT(*) FROM analyses GROUP BY classification")
    class_rows = cursor.fetchall()
    class_map = {row[0]: row[1] for row in class_rows}

    scams_detected = class_map.get("Likely Scam", 0)
    suspicious_count = class_map.get("Suspicious", 0)
    safe_count = class_map.get("Likely Safe", 0)

    # Risk level distribution
    cursor.execute("SELECT risk_level, COUNT(*) FROM analyses GROUP BY risk_level")
    risk_rows = cursor.fetchall()
    risk_distribution = {row[0]: row[1] for row in risk_rows}

    # Category breakdown (top 8)
    cursor.execute("""
    SELECT category, COUNT(*) as cnt 
    FROM analyses 
    WHERE category != 'Legitimate' 
    GROUP BY category 
    ORDER BY cnt DESC 
    LIMIT 8
    """)
    category_breakdown = [{"category": row["category"], "count": row["cnt"]} for row in cursor.fetchall()]

    # Analysis types breakdown
    cursor.execute("SELECT input_type, COUNT(*) as cnt FROM analyses GROUP BY input_type")
    type_breakdown = [{"type": row["input_type"], "count": row["cnt"]} for row in cursor.fetchall()]

    # Average risk score
    cursor.execute("SELECT AVG(risk_score) FROM analyses")
    avg_score_row = cursor.fetchone()[0]
    avg_risk_score = round(float(avg_score_row), 1) if avg_score_row else 0.0

    conn.close()

    return {
        "total_analyses": total_analyses,
        "scams_detected": scams_detected,
        "suspicious": suspicious_count,
        "safe": safe_count,
        "avg_risk_score": avg_risk_score,
        "risk_distribution": risk_distribution,
        "categories": category_breakdown,
        "types": type_breakdown
    }

@router.get("/threat-intel")
def get_threat_intel():
    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute("""
    SELECT id, indicator_type, value, risk_level, category, description, source, detected_at
    FROM threat_intel
    ORDER BY detected_at DESC
    """)
    rows = cursor.fetchall()
    conn.close()

    items = [dict(r) for r in rows]
    return {
        "total_threats": len(items),
        "threats": items,
        "status": "active_monitoring"
    }

@router.get("/admin/metrics")
def get_admin_metrics(current_user: Optional[dict] = Depends(get_current_user)):
    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT COUNT(*) FROM users")
    total_users = cursor.fetchone()[0]
    cursor.execute("SELECT COUNT(*) FROM analyses")
    total_analyses = cursor.fetchone()[0]
    conn.close()

    ml_metrics = {}
    if os.path.exists(METRICS_PATH):
        try:
            with open(METRICS_PATH, "r") as f:
                ml_metrics = json.load(f)
        except Exception as e:
            ml_metrics = {"error": f"Could not load ML metrics: {str(e)}"}

    return {
        "system_status": "Healthy (All micro-services nominal)",
        "total_registered_users": total_users,
        "total_analyses_logged": total_analyses,
        "active_models": {
            "nlp_text_pipeline": "TF-IDF + Calibrated Logistic Regression (v1.2)",
            "url_classifier": "Ensemble Random Forest (120 Estimators, v1.2)",
            "ocr_pipeline": "Tesseract Engine with Heuristic Fallback"
        },
        "model_evaluation": ml_metrics
    }
